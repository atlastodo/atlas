/** A lexicon with every phrase passed through {@link fold}, so lookups are plain comparisons. */
function folded(lex: QuickAddLexicon): QuickAddLexicon {
  const keys = <T>(rec: Record<string, T>) =>
    Object.fromEntries(Object.entries(rec).map(([k, v]) => [fold(k), v])) as Record<string, T>;
  const list = (xs: string[]) => xs.map(fold);
  return {
    ...lex,
    one: list(lex.one),
    gluedTimePrefixes: list(lex.gluedTimePrefixes ?? []),
    relativeDays: keys(lex.relativeDays),
    weekdays: keys(lex.weekdays),
    months: keys(lex.months),
    units: keys(lex.units),
    inPrefixes: list(lex.inPrefixes),
    nextPrefixes: list(lex.nextPrefixes),
    nextSuffixes: list(lex.nextSuffixes),
    thisPrefixes: list(lex.thisPrefixes),
    leadIns: list(lex.leadIns),
    monthConnectors: list(lex.monthConnectors),
    every: list(lex.every),
    single: keys(lex.single),
    fromCompletion: list(lex.fromCompletion),
    timePrefixes: keys(lex.timePrefixes),
    timeSuffixes: list(lex.timeSuffixes),
    noon: list(lex.noon),
    midnight: list(lex.midnight),
  };
}

const LEXICONS: Record<string, QuickAddLexicon> = Object.fromEntries(
  Object.entries(SOURCES).map(([code, lex]) => [code, folded(lex)]),
);

/**
 * The (folded) lexicons to match for a UI language such as "de" or "pt-BR", in order: its own, then
 * English. English alone for English, no language, or one without a lexicon.
 */
export function quickAddLexicons(language: string | undefined): QuickAddLexicon[] {
  const base = (language ?? "").toLowerCase().split(/[-_]/)[0] ?? "";
  const own = LEXICONS[base];
  return own && base !== "en" ? [own, LEXICONS.en!] : [LEXICONS.en!];
}
