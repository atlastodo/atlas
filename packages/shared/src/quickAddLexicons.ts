import type { Freq } from "./recurrence";

/**
 * Quick-add vocabulary, one lexicon per UI language. `quickAddParse` matches the UI language's
 * lexicon first and English after it, so English phrases work in every language. Every phrase is
 * lowercase and space-separated, and is matched accent-insensitively ({@link fold}), so "manana",
 * "lunedi" and "uebermorgen" work as well as the proper spelling.
 */
export interface QuickAddLexicon {
  /** Month before day ("jun 3") as well as day before month ("3 jun"). */
  monthFirst?: boolean;
  /** Words for a count of one: "in a week", "om en uge". */
  one: string[];
  /** A unit straight after an `inPrefixes` word means one of it: Polish "za tydzień". */
  inBareUnit?: boolean;
  /** Time prefixes that may be glued to the hour: Danish "kl17", "kl.9:30". */
  gluedTimePrefixes?: string[];
  /** Phrases that name a day relative to today: "morgen" → 1. */
  relativeDays: Record<string, number>;
  /** Weekday names and their inflected/plural forms, Sunday = 0. */
  weekdays: Record<string, number>;
  /** Month names (and the genitive forms dates use), January = 0. */
  months: Record<string, number>;
  /** Day/week/month/year in every form a count can take. */
  units: Record<string, Freq>;
  /** Before a count and unit: "in 3 Tagen" → "in". */
  inPrefixes: string[];
  /** Before a weekday or unit: "nächsten Montag". */
  nextPrefixes: string[];
  /** After a weekday or unit: "lundi prochain". */
  nextSuffixes: string[];
  /** Before a weekday: "diesen Freitag". */
  thisPrefixes: string[];
  /**
   * Words consumed in front of a date only when the date follows: "am Montag", "el lunes",
   * "w środę", "la semaine prochaine". Never matched on their own.
   */
  leadIns: string[];
  /** Between a day number and its month: "3 de marzo". */
  monthConnectors: string[];
  /** Before a weekday, a unit, or a count and unit: "jede Woche", "alle 2 Wochen". */
  every: string[];
  /** One word or phrase that is a whole rule: "täglich" → daily. */
  single: Record<string, Freq>;
  /** After a rule: schedule from the completion date, like `every!`. */
  fromCompletion: string[];
  /**
   * Before a time. `true` accepts a bare hour ("um 17"); `false` needs minutes ("o 17:30"), for a
   * prefix that is also an everyday word.
   */
  timePrefixes: Record<string, boolean>;
  /** A word after the hour: "17 Uhr". */
  timeSuffixes: string[];
  /** Letter glued to the hour: "17h30" (French), "17u" (Dutch). */
  hourLetter?: string;
  noon: string[];
  midnight: string[];
}

/** Lowercase, strip accents and unify apostrophes, for accent-insensitive matching. */
export function fold(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/ł/g, "l")
    .replace(/ß/g, "ss")
    .replace(/[’‘`]/g, "'");
}

